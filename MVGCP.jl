        end
        value = value*λ
        value += 1
    end
    s = zeros(T)
    s2 = zeros(ti_rounded)
    for t in 1:T
        s[t] = s_0[t]*f1(t)
    end
    for t in 1:ti_rounded
        if f2(t) > 0
            s2[t] = s_02[t]*f2(t)
        else
            s2[t] = 0
        end
    end
    s_tot = zeros(n_steps)

    for j in 1:rydberg_states
        for t in 1:(ti_rounded)
