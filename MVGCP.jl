    berry[n_steps, :] = berry[n_steps-1, :]
    dynamic = @.exp((dynamic.*im))
    berry = @.exp((berry)*im)
    total_phase = zeros(ComplexF64, n_steps, n_eig)
    for i in 1:n_steps
        for j in 1:n_eig
            total_phase[i, j] = dynamic[i, j]*berry[i,j]
        end
    end
end

