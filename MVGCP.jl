    s_0 = LinRange(0, 1, T)
    s_02 = LinRange(0, 1, ti_rounded)

    function f1(t)
        λ = sin(pi*(t/T))
        ω_A1 = [pi*k*(1+r1[k])/T for k in 1:N_c]
        ω_B1 = [pi*(k-N_c)*(1+r1[k])/T for k in (N_c+1):(2*N_c)]
        value = 0
        for k in 1:N_c
