function hamiltonian(Δ, Ω, c6, node_locations, t; ϕ_s=0)
    """Generate total Hamiltonian of system using above parameters; sum of drive + interaction Hamiltonians"""
    rydberg_states = size(c6)[1]
    n_qudits = size(node_locations)[1]
    id = 1 * Matrix{Float64}(I, rydberg_states+1, rydberg_states+1) # single-qudit identity matrix, dimension |g> + all |r_i>
    single = zeros(ComplexF64, rydberg_states+1, rydberg_states+1, n_qudits)

    # populate single qubit hamiltonian
    if ϕ_s == 0
        for i in 1:rydberg_states
            for j in 1:n_qudits
                single[i+1, i+1, j] = -Δ[t, i, j]
                single[1, i+1, j] = 0.5*Ω[t, i, j]
                single[i+1, 1, j] = 0.5*Ω[t, i, j]
            end
        end
    else
        for i in 1:rydberg_states
            for j in 1:n_qudits
                single[i+1, i+1, j] = -Δ[t, i, j]
                single[1, i+1, j] = 0.5*Ω[t, i, j]*exp(im*ϕ_s[t, i, j])
                single[i+1, 1, j] = 0.5*Ω[t, i, j]*exp(-1*im*ϕ_s[t, i, j])
            end
        end
    end

    # generate placeholder matrix of total dimension of end product hamiltonian
    drive = zeros((rydberg_states+1)^n_qudits, (rydberg_states+1)^n_qudits)

    # tensor product sum of single qubit Hamiltonians
    for i in 1:n_qudits
        left_product = id
        drive_temp = id
        i == 1 ? drive_temp = single[:,:,i] : drive_temp = id
        for m in 2:n_qudits
            m == i ? left_product = single[:,:,i] : left_product = id
            drive_temp = kron(left_product, drive_temp)
        end
        drive += drive_temp
    end
    
    # placeholder matrix for interaction Hamiltonian
    dim = size(id)[1]^n_qudits
    h_int_total = zeros(dim, dim)

    #= tensor product sum for interaction Hamiltonian: for every |r_p, r_q><r_p, r_q|(i,j) coefficient (i.e. matrix element)
    generates a dim x dim matrix with that coefficient in the correct place; a sum then runs over every p,q (including q,p).
    This procedure runs over every pair of qudits i,j. Each |r_p, r_q><r_p, r_q|(i,j) coefficient matrix is generated by the
    square root of the coefficient value in the required location (and zeros elsewhere) replacing the identity matrix in the
    positions i,j in the tensor product, i.e. I_1 * I_2 * |r_1><r_1|(3) * I_4 * |r_2><r_2|(5) * I_6 is the term in a six-qudit
    setup for the intra-rydberg interaction between the rydberg states r_1 and r_2 between qudits 3 and 5; note there must
    also be an additional term with r_1 and r_2 switched between the same qudits for these two rydberg states. =#
    for p in 1:rydberg_states
        for q in 1:rydberg_states
            for i in 1:n_qudits
                for j in 1:n_qudits
                    if i != j
                        h_int_temp = id
                        left_product = id
                        int_i = zeros(ComplexF64, rydberg_states+1, rydberg_states+1)
                        int_j = zeros(ComplexF64, rydberg_states+1, rydberg_states+1)
                        distance = sqrt((node_locations[i,1] - node_locations[j,1])^2 + ((node_locations[i,2] - node_locations[j,2])^2) + ((node_locations[i,3] - node_locations[j,3])^2))
                        int_i[p+1, p+1] = sqrt(complex(c6[p, q])/(distance^6))
                        int_j[q+1, q+1] = sqrt(complex(c6[p, q])/(distance^6))
                        i == 1 ? h_int_temp = int_i : j == 1 ? h_int_temp = int_j : h_int_temp = id
                        for m in 2:n_qudits
                            m == i ? left_product = int_i : m == j ? left_product = int_j : left_product = id
                            h_int_temp = kron(left_product, h_int_temp)
                        end
                        h_int_total += h_int_temp
                    end
                end
            end
        end
    end
    return  drive + h_int_total
end

function total_hamiltonian(n_steps; ϕ_s=0)
    dim = size(hamiltonian(Δ, Ω, c6, node_locations, 1; ϕ_s))[1]
    total_hamiltonian = zeros(ComplexF64, dim, dim, n_steps)
    for t in 1:n_steps
        total_hamiltonian[:,:,t] .= hamiltonian(Δ, Ω, c6, node_locations, t; ϕ_s)[:,:]
    end
    return total_hamiltonian
end

function trotter_evolve(h_tot, initial_state, evolve_time)
    dim = size(h_tot)[1]
    n_steps = size(h_tot)[3]
    states = zeros(ComplexF64, dim, n_steps+1)
    states[:,1] = initial_state
    dt = evolve_time/n_steps
    for t in 1:n_steps
        h = h_tot[:,:,t] |> sparse
        psi = states[:,t]
        states[:,t+1] = expmv!(-im*dt, h, psi)
    end
    return states, h_tot
end

function partial_trace(density_matrix, rydberg_states, qudit_index)
    n_qudits = Int(log((rydberg_states+1), size(density_matrix)[1]))
    ones = zeros(rydberg_states+1, rydberg_states+1) .+ 1

    # generates set of matrices, with each matrix corresponding to each diagonal of the qudit to be summed over
    diagonal_markers = zeros(size(density_matrix)[1], size(density_matrix)[1], (rydberg_states+1))
    for i in 1:(rydberg_states+1)
        marker = zeros((rydberg_states+1), (rydberg_states+1))
        marker[i,i] = 1
        left_product = ones
        marked_temp = ones
        qudit_index == 1 ? marked_temp = marker : marked_temp = ones
        for i in 2:n_qudits
            i == qudit_index ? left_product = marker : left_product = ones
            marked_temp = kron(left_product, marked_temp)
        end
        diagonal_markers[:,:,i] = marked_temp
    end

    # rdm placeholder
    reduced_density_matrix = zeros(ComplexF64, (rydberg_states+1)^(n_qudits-1), (rydberg_states+1)^(n_qudits-1))

    # fills new reduced density matrix
    for k in eachindex(diagonal_markers[1,1,:])
        m = 1
        for i in eachindex(density_matrix[:,1])
            shift_m = false
            n = 1
            for j in eachindex(density_matrix[1,:])
                if diagonal_markers[i,j,k] != 0
                    reduced_density_matrix[m,n] += density_matrix[i,j]
                    n += 1
                    shift_m = true
                end
            end
            shift_m == true ? m += 1 : m += 0
        end
    end
    return reduced_density_matrix
end

function test_hermitian(h)
    h1 = h * h'
    h2 = h * h
    error_pairs = []
    for i in 1:size(h)[1]
        for j in i:size(h)[2]
            if !isequal(h1[i,j], h2[i,j]) && ((!isequal(abs(imag(h1[i,j])),0.0) && !isequal(abs(imag(h2[i,j])),0.0)) || !isequal(real(h1[i,j]), real(h2[i,j])))
                push!(error_pairs, [h1[i,j], h2[i,j]])
            end
        end
    end
    isempty(error_pairs)
end

function half_blackman(n_steps, forward=true)
    factor = 0
    if forward == false
        factor = 1
    end
    profile = zeros(n_steps)
    for i in 0:(n_steps-1)
        profile[i+1] = 0.42 - 0.5*cos((pi*(i+factor*n_steps))/(n_steps-1)) + 0.08*cos((2*pi*(i+factor*n_steps))/(n_steps-1))
    end
    return profile
end

# parameter initialisation for z2 crystal
begin
    c6 = [
        5_420_503_000
    ] #= matrix c6{ij} for rydberg interaction coefficient between qudits i,j;
         diagonals are therefore the intra-, off-diagonals the inter-rydberg coefficients;
         units are GHz μm^6 =#

    rydberg_states = size(c6)[1] # no. of rydberg states used

    evolve_time = (8e-6)*(21//20) # total evolution time in units of s
    n_steps = Int(400*(21//20)) # no. of timesteps

    Δ_max = [1 ; 1 ; 1 ; 1 ; 1 ; 1 ; 1].*10*((2pi)*1e6) # one detuning range for each rydberg state in units of GHz
    function Δ_sweep(Δ)
        sweep = zeros(n_steps)
        sweep[1:Int(n_steps*(1//42))] .= -1*Δ
        sweep[(Int(n_steps*(1//42))+1):Int(n_steps*(41//42))] .= (LinRange(-1*(Δ^(1/3)),Δ^(1/3), Int(n_steps*(20//21))).^3)
        sweep[(Int(n_steps*(41//42))+1):n_steps] .= Δ
        return sweep
    end

    Ω_max = [1 ; 1 ; 1 ; 1 ; 1 ; 1 ; 1].*2.5*((2pi)*1e6) # one rabi frequency for between |g> and |r_i> for each rydberg state in units of GHz
    function Ω_sweep(Ω)
        sweep = zeros(n_steps)
        sweep[1:Int(n_steps*(1//42))] .= LinRange(0, Ω, Int(n_steps*(1//42)))
        sweep[(Int(n_steps*(1//42))+1):Int(n_steps*(41//42))] .= Ω
        sweep[(Int(n_steps*(41//42))+1):n_steps] .= LinRange(Ω, 0, Int(n_steps*(1//42)))
        return sweep
    end

    
    blockade_radius = (c6[1]/Ω_max[1])^(1/6)
    lattice_spacing = 0.7*blockade_radius
    node_locations = [0 0 0 ; 1*lattice_spacing 0 0 ; 2*lattice_spacing 0 0 ; 3*lattice_spacing 0 0 ; 4*lattice_spacing 0 0 ; 5*lattice_spacing 0 0 ; 6*lattice_spacing 0 0] # location of the qudits (representing nodes of the graph) in units of μm

    Δ = zeros(n_steps, rydberg_states, size(node_locations)[1])
    Ω = zeros(n_steps, rydberg_states, size(node_locations)[1])
    for i in eachindex(Δ_max[1,:]), k in eachindex(Ω_max[1,:]) # loop over rydberg states
        for j in eachindex(Δ_max[:,1]), l in eachindex(Ω_max[:,1]) # loop over qudits
            for t in 1:n_steps
                Δ[t, i, j] = Δ_sweep(Δ_max[j, i])[t] # Cubic sweep of over each detuning
                Ω[t, k, l] = Ω_sweep(Ω_max[l, k])[t] # rabi frequency remains constant over sweep
            end
        end
    end

    initial_state = [x > 1 ? 0 : x for x in 1:((rydberg_states+1)^size(node_locations)[1])] # ground state, all qudits |0>
    ts = [(i-1)*(evolve_time/n_steps) for i in 1:(n_steps+1)]
end

